#!/usr/bin/env python3
"""Build this NES project and check the result against your own copy of the game, byte for byte.

    python build.py                  make the disassembly from your copy, build it, compare
    python build.py --no-documented  without the documented routines (their bytes, as the disassembly has them)

Your copy (baserom.nes) is disassembled into build/disassembly/ on every build: each PRG bank a ca65 segment at the
address it's shown at, each function in layout.json as 6502 instructions (tools/mos6502.py) under its name, with a
label at every jump target and the notes in comments.txt above it; what isn't a function as bytes; each routine
documented in assembly (documented/) in place of its bytes; the header, trainer and graphics included from your copy.
ca65 and ld65 assemble and link it. Generated by decomp.wtf (https://decomp.wtf).
"""

from __future__ import annotations

import bisect
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "tools"))
import mos6502  # noqa: E402  (decomp.wtf's 6502 disassembler, next to this file)

B = json.loads((ROOT / "build.json").read_text(encoding="utf-8"))
L = json.loads((ROOT / "layout.json").read_text(encoding="utf-8"))
OUT = ROOT / "build"
BRANCH = re.compile(r"^(jsr|jmp|bcc|bcs|beq|bne|bmi|bpl|bvc|bvs) \$([0-9a-f]{4})$")
ABSOLUTE = re.compile(r"^(\w+) \$([0-9a-f]{4})(,[xy])?$")
NAME = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")
GLOBAL = re.compile(r"^\s*([A-Za-z][A-Za-z0-9_]*):", re.M)
WORD = re.compile(r"(?<![.@\w])[A-Za-z_]\w*")
WRITES = ("sta", "stx", "sty", "inc", "dec", "asl", "lsr", "rol", "ror")


def fail(msg: str) -> None:
    sys.exit(f"error: {msg}")


def tools() -> tuple[Path, Path]:
    """(ca65, ld65): decomp.wtf's pinned cc65 when it's installed, else CC65 (a folder) or PATH."""
    try:
        from decompnet import toolchains

        if toolchains.installed("cc65"):
            base = toolchains.path("cc65")
            exe = ".exe" if (base / "ca65.exe").exists() else ""
            return base / f"ca65{exe}", base / f"ld65{exe}"
    except ImportError:
        pass
    folder = os.environ.get("CC65")
    if folder and (Path(folder) / "ca65").exists():
        return Path(folder) / "ca65", Path(folder) / "ld65"
    asm, link = shutil.which("ca65"), shutil.which("ld65")
    if not (asm and link):
        fail("needs cc65: install decomp.wtf (it pins it), or put ca65 and ld65 on PATH (or set CC65 to their folder)")
    return Path(asm), Path(link)


def run(argv: list, cwd: Path) -> None:
    proc = subprocess.run([str(a) for a in argv], cwd=cwd, capture_output=True, text=True, encoding="utf-8",
                          errors="replace")
    if proc.returncode != 0:
        fail(f"{Path(str(argv[0])).name} failed:\n{(proc.stdout + proc.stderr).strip()[-2000:]}")


def comments() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    path = ROOT / "comments.txt"
    for line in path.read_text(encoding="utf-8").splitlines() if path.exists() else []:
        label, sep, text = line.partition(": ")
        if sep and NAME.match(label):
            out.setdefault(label, []).append(text)
    return out


def hardware() -> tuple[dict[int, str], dict[int, str]]:
    """{address: name} for reads and for writes, as include/hardware.inc names the hardware."""
    names = {}
    for line in (ROOT / "include" / "hardware.inc").read_text(encoding="utf-8").splitlines():
        if (m := re.match(r"^(\w+) = \$([0-9A-Fa-f]+)$", line)):
            names[m.group(1)] = int(m.group(2), 16)
    read, write = {}, {}
    for name, v in sorted(names.items()):
        if v >= 0x8000:
            write.setdefault(v, name)  # (a mapper's register: written)
        else:
            read.setdefault(v, name)
            write.setdefault(v, name)
    if "APU_FRAME" in names:
        write[names["APU_FRAME"]] = "APU_FRAME"
        read[names["APU_FRAME"]] = "JOY2"
    return read, write


class Disassembly:
    """The game's PRG as ca65 source: one segment per bank, at the address it's shown at."""

    def __init__(self, image: bytes, documented: bool):
        self.image = image
        prg = L["prg"]
        self.prg_off, self.prg_size, self.unit, self.bases = prg["offset"], prg["size"], prg["unit"], prg["banks"]
        self.banks = len(self.bases)
        self.data = bytearray(len(image))  # 1: bytes the map has as data
        for flat, n, _kind in L["regions"]:
            self.data[flat:flat + n] = b"\x01" * max(0, min(n, len(image) - flat))
        self.funcs = sorted((f for f in L["functions"] if self.prg_off <= f["flat"] < self.prg_off + self.prg_size),
                            key=lambda f: f["flat"])
        self.insn: dict[int, tuple[str, int, int]] = {}
        self.labels: dict[int, str] = {}
        self.documented = {e["flat"]: e for e in L["documented"]} if documented else {}
        self.defines: dict[str, int] = {}
        self.left: list[tuple[str, str]] = []
        self.placed, self.done = 0, {}
        self.read, self.write = hardware()

    def bank_of(self, flat: int) -> int:
        return (flat - self.prg_off) // self.unit

    def at(self, flat: int) -> int:
        """The address the byte at file offset `flat` is shown at (its bank's)."""
        return self.bases[self.bank_of(flat)] + (flat - self.prg_off) % self.unit

    def resolve(self, target: int, from_flat: int) -> int | None:
        """The file offset a jump to `target` from code at `from_flat` reaches, when the build can tell: its own
        bank's window, or a window only one bank is shown at."""
        if target < 0x8000:
            return None
        banks = [b for b in range(self.banks) if self.bases[b] <= target < self.bases[b] + self.unit]
        own = self.bank_of(from_flat)
        bank = own if own in banks else banks[0] if len(banks) == 1 else None
        if bank is None:
            return None
        return self.prg_off + bank * self.unit + target - self.bases[bank]

    def decode(self) -> None:
        for f in self.funcs:
            flat, cpu, n = f["flat"], f["cpu"], f["size"]
            if cpu != self.at(flat):
                continue  # it runs elsewhere than its bank is shown: its bytes, as bytes
            off = 0
            while off < n:
                a = flat + off
                if self.data[a]:
                    off += 1
                    continue
                text, ln = mos6502.decode(self.image[a:a + 3], cpu + off)
                if text.startswith("db ") or off + ln > n or self.bank_of(a) != self.bank_of(a + ln - 1):
                    break
                self.insn.setdefault(a, (text, ln, cpu + off))
                off += ln
        starts = sorted(self.documented)
        self.emitted, covered = {}, -1
        for a in sorted(self.insn):
            ln = self.insn[a][1]
            k = bisect.bisect_right(starts, a)
            if a >= covered and not (k < len(starts) and starts[k] < a + ln):
                self.emitted[a] = self.insn[a]
                covered = a + ln
        self.inside = set()
        for a, (_t, ln, _c) in self.emitted.items():
            self.inside.update(range(a + 1, a + ln))

    def name_targets(self) -> None:
        names = {f["flat"]: f["name"] for f in self.funcs if f.get("name") and NAME.match(f["name"])}
        runs_at = {f["flat"]: f["cpu"] for f in self.funcs}
        for a, (text, _ln, _cpu) in self.emitted.items():
            if (m := BRANCH.match(text)) and (to := self.resolve(int(m.group(2), 16), a)) is not None \
                    and to not in self.inside and self.at(to) == int(m.group(2), 16):
                self.labels.setdefault(to, names.get(to) or f"L{self.bank_of(to):02X}_{self.at(to):04X}")
        for flat, name in names.items():
            if flat not in self.inside and self.at(flat) == runs_at[flat]:
                self.labels[flat] = name

    def operand(self, a: int, text: str) -> list[str]:
        """An instruction with the build's names, as ca65 takes it (one or two lines)."""
        if (m := BRANCH.match(text)):
            target = int(m.group(2), 16)
            to = self.resolve(target, a)
            label = self.labels.get(to) if to is not None and self.at(to) == target else None
            return [f"{m.group(1)} {label or f'${target:04x}'}"]
        if text.startswith("brk "):
            return ["brk", f".byte {text[4:]}"]
        if text.startswith("db "):
            return [".byte " + text[3:]]
        if (m := ABSOLUTE.match(text)):
            value = int(m.group(2), 16)
            op = m.group(1)
            name = (self.write if op in WRITES else self.read).get(value)
            if name:
                return [f"{op} {name}{m.group(3) or ''}"]
            if value < 0x100:
                return [f"{op} a:${value:04x}{m.group(3) or ''}"]  # (the 3-byte form: ca65 would write zero page)
        return [text]

    def substitute(self, flat: int, e: dict) -> list[str] | None:
        text = (ROOT / e["file"]).read_text(encoding="utf-8")
        own = set(GLOBAL.findall(text))
        end = flat + e["size"]
        if flat in self.inside or end in self.inside:
            self.left.append((e["name"], "its ends fall inside instructions here"))
            return None
        for a, name in self.labels.items():  # (others reach these: by number does it)
            if flat <= a < end and name not in own:
                self.defines[name] = self.at(a)
        self.placed += 1
        self.done[flat] = True
        return [f"; documented in assembly: {e['file']}", *text.rstrip().splitlines(), ""]

    def bank(self, b: int, notes: dict[str, list[str]]) -> str:
        lo = self.prg_off + b * self.unit
        hi = min(lo + self.unit, self.prg_off + self.prg_size)
        lines = [f'.segment "BANK{b:03d}"', f".org ${self.bases[b]:04X}"]
        p, pending = lo, []

        def flush():
            for k in range(0, len(pending), 16):
                lines.append("    .byte " + ", ".join(f"${v:02x}" for v in pending[k:k + 16]))
            pending.clear()
        while p < hi:
            if p in self.documented and (body := self.substitute(p, self.documented[p])) is not None:
                flush()
                lines += [f"; {t}" for t in notes.get(self.documented[p]["name"], [])] + body
                p += self.documented[p]["size"]
                continue
            if p in self.labels:
                flush()
                lines += [f"; {t}" for t in notes.get(self.labels[p], [])] + [f"{self.labels[p]}:"]
            if p in self.emitted:
                flush()
                text, ln, _cpu = self.emitted[p]
                lines += ["    " + x for x in self.operand(p, text)]
                p += ln
            else:
                pending.append(self.image[p])
                p += 1
        flush()
        return "\n".join(lines + [""])

    def used_names(self) -> None:
        """Names a documented routine uses that no label here gives: by number."""
        placed = set(self.labels.values())
        functions = {f["name"]: f["cpu"] for f in self.funcs if f.get("name")}
        for e in self.documented.values():
            text = (ROOT / e["file"]).read_text(encoding="utf-8")
            used = {w for line in text.splitlines() for w in WORD.findall(line.split(";")[0])}
            own = set(GLOBAL.findall(text))
            self.defines.update({n: functions[n] for n in used if n in functions and n not in placed and n not in own})


def main(argv: list[str]) -> int:
    image_path = ROOT / B["image"]
    if not image_path.exists():
        fail(f"put your own copy of the game here as {B['image']}")
    data = image_path.read_bytes()
    if hashlib.sha1(data).hexdigest() != B["sha1"]:
        fail(f"{B['image']} isn't the version this project is for (its sha1 differs)")
    asm, link = tools()
    folder = OUT / "disassembly"
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)
    shutil.copyfile(image_path, folder / B["image"])  # (the header and graphics are included from it)
    print("disassembling your copy (with the project's names)")
    d = Disassembly(data, documented="--no-documented" not in argv)
    d.decode()
    d.name_targets()
    d.used_names()
    notes = comments()
    banks = [d.bank(b, notes) for b in range(d.banks)]
    for e in d.documented.values():
        if not d.done.get(e["flat"]) and e["name"] not in {n for n, _ in d.left}:
            d.left.append((e["name"], "its start falls inside what comes before it here"))
    for name, why in d.left:
        print(f"left as bytes: {name}: {why}")
    names = (ROOT / "documented" / "names.inc").read_text(encoding="utf-8") if (ROOT / "documented" / "names.inc").exists() else ""
    names += "".join(f"{n} = ${v:04X}\n" for n, v in sorted(d.defines.items()))
    (folder / "names.inc").write_text(names, encoding="utf-8")
    shutil.copyfile(ROOT / "include" / "hardware.inc", folder / "hardware.inc")
    prg, chr_ = L["prg"], L["chr"]
    game = ['.include "hardware.inc"', '.include "names.inc"', '.segment "HEADER"',
            f'.incbin "{B["image"]}", 0, {prg["offset"]}']
    memory = [f"    HDR: start = 0, size = ${prg['offset']:X}, file = %O;"]
    segments = ["    HEADER: load = HDR, type = ro;"]
    for b, text in enumerate(banks):
        (folder / f"bank_{b:03d}.s").write_text(text, encoding="utf-8")
        game.append(f'.include "bank_{b:03d}.s"')
        size = min(prg["unit"], prg["size"] - b * prg["unit"])
        memory.append(f"    PRG{b:03d}: start = ${prg['banks'][b]:04X}, size = ${size:X}, file = %O, fill = yes, fillval = $FF;")
        segments.append(f"    BANK{b:03d}: load = PRG{b:03d}, type = ro;")
    if chr_["size"]:
        game += ['.segment "CHR"', f'.incbin "{B["image"]}", {chr_["offset"]}, {chr_["size"]}']
        memory.append(f"    CHR: start = 0, size = ${chr_['size']:X}, file = %O;")
        segments.append("    CHR: load = CHR, type = ro;")
    (folder / "game.s").write_text("\n".join(game) + "\n", encoding="utf-8")
    (folder / "game.cfg").write_text("MEMORY {\n" + "\n".join(memory) + "\n}\nSEGMENTS {\n" + "\n".join(segments)
                                     + "\n}\n", encoding="utf-8")
    print(f"{d.placed} documented routines in place of their bytes")
    run([asm, "-o", "game.o", "game.s"], folder)
    run([link, "-C", "game.cfg", "-o", "game.nes", "game.o"], folder)
    built = (folder / "game.nes").read_bytes()
    shutil.copyfile(folder / "game.nes", OUT / "game.nes")
    if built == data:
        print("identical: build/game.nes is your copy of the game, byte for byte")
        return 0
    at = next((i for i, (a, b) in enumerate(zip(built, data)) if a != b), min(len(built), len(data)))
    print(f"differs: build/game.nes first differs from your copy at ${at:06x} ({len(built)} vs {len(data)} bytes)")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
