#!/usr/bin/env python3
"""Build this Master System / Game Gear project and check the result against your own copy of the game, byte for byte.

    python build.py                  make the disassembly from your copy, build it, compare
    python build.py --no-documented  without the documented routines (their bytes, as the disassembly has them)

Your copy (baserom.sms or baserom.gg) is disassembled into build/disassembly/ on every build: each function in
layout.json as Z80 instructions (tools/z80.py) at the address it runs at, under its name, with a label at every jump
target and the notes in comments.txt above it; what isn't a function as bytes; each routine documented in assembly
(documented/) in place of its bytes. WLA-DX assembles and links it. Edit the names, comments and documented routines
here; the disassembly itself is made from your copy and stays out of git. Generated by decomp.wtf (https://decomp.wtf).
"""

