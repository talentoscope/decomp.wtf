from __future__ import annotations

import bisect
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT / "tools"))
import z80  # noqa: E402  (decomp.wtf's Z80 disassembler, next to this file)

B = json.loads((ROOT / "build.json").read_text(encoding="utf-8"))
L = json.loads((ROOT / "layout.json").read_text(encoding="utf-8"))
OUT = ROOT / "build"
BANK = 0x4000
COND = r"(?:nz|z|nc|c|po|pe|p|m)"
BRANCH = re.compile(rf"^(jp|jr|call|djnz)( {COND}, | )\$([0-9a-f]{{4}})$")
MEMORY = re.compile(r"\(\$([0-9a-f]{4})\)")
PORT = re.compile(r"^(in a, |out )\(\$([0-9a-f]{2})\)")
LABEL_LINE = re.compile(r"^([A-Za-z][A-Za-z0-9_]*):\s*$")
NAME = re.compile(r"^[A-Za-z][A-Za-z0-9_]*$")
GLOBAL = re.compile(r"^\s*([A-Za-z][A-Za-z0-9_]*):", re.M)
WORD = re.compile(r"(?<![.@\w])[A-Za-z_]\w*")
RELATIVE = re.compile(r"^\s*(?:@*[A-Za-z_]\w*:\s*)*(?:jr|djnz)\b[^;]*?\b([A-Za-z_]\w*)\s*(?:;|$)", re.M)


def fail(msg: str) -> None:
    sys.exit(f"error: {msg}")


def tools() -> tuple[Path, Path]:
    """(wla-z80, wlalink): decomp.wtf's pinned WLA-DX when it's installed, else WLA_DX (a folder) or PATH."""
    try:
        from decompnet import toolchains

        if toolchains.installed("wla-dx"):
            base = toolchains.path("wla-dx")
            candidates = (
                (base / "wla-z80.exe", base / "wlalink.exe"),
                (base / "wla-z80", base / "wlalink"),
                (base / "build" / "binaries" / "wla-z80", base / "build" / "binaries" / "wlalink"),
            )
            for asm, link in candidates:
                if asm.is_file() and link.is_file():
                    return asm, link
    except ImportError:
        pass
    folder = os.environ.get("WLA_DX")
    if folder and (Path(folder) / "wla-z80").exists():
        return Path(folder) / "wla-z80", Path(folder) / "wlalink"
    asm, link = shutil.which("wla-z80"), shutil.which("wlalink")
    if not (asm and link):
        fail("needs WLA-DX: install decomp.wtf (it pins it), or put wla-z80 and wlalink on PATH (or set WLA_DX to "
             "their folder)")
    return Path(asm), Path(link)


def run(argv: list, cwd: Path) -> None:
    try:
        proc = subprocess.run([str(a) for a in argv], cwd=cwd, capture_output=True, text=True, timeout=120,
                              encoding="utf-8", errors="replace")
    except subprocess.TimeoutExpired:
        fail(f"{Path(str(argv[0])).name} timed out after 120 seconds")
    if proc.returncode != 0:
        fail(f"{Path(str(argv[0])).name} failed:\n{(proc.stdout + proc.stderr).strip()[-2000:]}")


def comments() -> dict[str, list[str]]:
    """label -> its comment lines, from comments.txt (`Label: text`, one line each)."""
    out: dict[str, list[str]] = {}
    path = ROOT / "comments.txt"
    for line in path.read_text(encoding="utf-8").splitlines() if path.exists() else []:
        label, sep, text = line.partition(": ")
        if sep and NAME.match(label):
            out.setdefault(label, []).append(text)
    return out


class Disassembly:
    """The game as WLA-DX source: one section per bank, at the slot its code runs from."""

    def __init__(self, image: bytes, documented: bool):
        self.image, self.size = image, len(image)
        self.banks = max(1, -(-self.size // BANK))
        bases = {int(b): v for b, v in L["banks"].items()}
        # (where nothing says: as at power-on, every bank where it is up to 48 KiB, else bank 1 in slot 1, the rest in 2)
        self.base = [bases.get(b, b * BANK if self.size <= 3 * BANK else 0x4000 if b == 1 else 0x8000) if b else 0
                     for b in range(self.banks)]
        self.data = bytearray(self.size)  # 1: bytes the map has as data (a routine's operands, tables)
        for flat, n, _kind in L["regions"]:
            self.data[flat:flat + n] = b"\x01" * max(0, min(n, self.size - flat))
        self.funcs = sorted((f for f in L["functions"] if 0 <= f["flat"] < self.size), key=lambda f: f["flat"])
        self.insn: dict[int, tuple[str, int, int]] = {}  # flat -> (text, length, the address it runs at)
        self.labels: dict[int, str] = {}  # flat -> label
        self.refs: dict[int, set[str]] = {}  # flat -> how it's reached: abs (jp, call) | rel (jr, djnz)
        self.documented = {e["flat"]: e for e in L["documented"]} if documented else {}
        self.defines: dict[str, int] = {}  # names documented routines need that aren't labels here
        self.left: list[tuple[str, str]] = []
        self.placed = 0  # documented routines in place of their bytes
        self.done: dict[int, bool] = {}

    def at(self, flat: int) -> int:
        """The address the byte at `flat` has in the build (its bank's slot)."""
        return flat if flat < BANK else self.base[flat // BANK] + flat % BANK

    def resolve(self, target: int, from_flat: int) -> int | None:
        """The ROM offset a jump to `target` from code at `from_flat` reaches, when the build can tell: bank 0, or the
        slot the code's own bank runs from."""
        if target < BANK:
            return target if target < self.size else None
        bank = from_flat // BANK
        if bank and self.base[bank] == target & 0xC000 and target < 0xC000:
            flat = bank * BANK + (target & (BANK - 1))
            return flat if flat < self.size else None
        return None

    def decode(self) -> None:
        for f in self.funcs:
            flat, cpu, n = f["flat"], f["cpu"], f["size"]
            if flat >= BANK and cpu - flat % BANK != self.base[flat // BANK]:
                continue  # it runs elsewhere than its bank's slot: its bytes, as bytes
            off = 0
            while off < n and flat + off < self.size:
                a = flat + off
                if self.data[a]:
                    off += 1
                    continue
                text, ln = z80.decode(self.image[a:a + 4], cpu + off)
                if text.startswith("db ") or off + ln > n or a // BANK != (a + ln - 1) // BANK:
                    break
                self.insn.setdefault(a, (text, ln, cpu + off))
                off += ln
        # what's emitted as an instruction: walking each bank, the instructions that don't overlap the one before,
        # nor run into a documented routine's start (its text goes there: what runs into it is bytes)
        starts = sorted(self.documented)
        self.emitted, covered = {}, -1
        for a in sorted(self.insn):
            ln = self.insn[a][1]
            k = bisect.bisect_right(starts, a)
            if a >= covered and not (k < len(starts) and starts[k] < a + ln):
                self.emitted[a] = self.insn[a]
                covered = a + ln
        self.inside = set()  # bytes inside an emitted instruction (no label can go there)
        for a, (_t, ln, _c) in self.emitted.items():
            self.inside.update(range(a + 1, a + ln))

    def name_targets(self) -> None:
        names = {f["flat"]: f["name"] for f in self.funcs if f.get("name") and NAME.match(f["name"])}
        runs_at = {f["flat"]: f["cpu"] for f in self.funcs}
        for a, (text, ln, _cpu) in self.emitted.items():
            if (m := BRANCH.match(text)) and (to := self.resolve(int(m.group(3), 16), a)) is not None \
                    and to not in self.inside and self.at(to) == int(m.group(3), 16):
                self.labels.setdefault(to, names.get(to) or f"L{to // BANK:02X}_{self.at(to):04X}")
                self.refs.setdefault(to, set()).add("rel" if m.group(1) in ("jr", "djnz") else "abs")
        for flat, name in names.items():  # every function its name, where it can go
            if flat not in self.inside and (flat < BANK or self.at(flat) == runs_at[flat]):
                self.labels[flat] = name

    def operand(self, a: int, text: str) -> str:
        """An instruction with the build's names: jump targets by label; a relative jump nobody named by where it
        goes; ports and the mapper by the hardware's names."""
        if (m := BRANCH.match(text)):
            target = int(m.group(3), 16)
            to = self.resolve(target, a)
            label = self.labels.get(to) if to is not None and self.at(to) == target else None
            if label is None and m.group(1) in ("jr", "djnz"):
                label = f"${target:04x}-CADDR-1"  # (WLA-DX reads a plain number there as the offset)
            return f"{m.group(1)}{m.group(2)}{label or f'${target:04x}'}"
        if (m := PORT.match(text)):
            port = int(m.group(2), 16)
            name = HW_PORTS.get((port, m.group(1).startswith("out")))
            if name:
                return text.replace(f"(${m.group(2)})", f"({name})", 1)
        if (m := MEMORY.search(text)) and int(m.group(1), 16) in HW_MAPPER:
            return text.replace(m.group(0), f"({HW_MAPPER[int(m.group(1), 16)]})", 1)
        if text.startswith("db "):
            return "." + text
        return text

    def substitute(self, flat: int, e: dict) -> list[str] | None:
        """A documented routine's text in place of its bytes, or None (with why) when it can't go in."""
        text = (ROOT / e["file"]).read_text(encoding="utf-8")
        own = set(GLOBAL.findall(text))
        end = flat + e["size"]
        if flat in self.inside or end in self.inside:
            self.left.append((e["name"], "its ends fall inside instructions here"))
            return None
        inner = {a: name for a, name in self.labels.items() if flat <= a < end and name not in own}
        if any("rel" in self.refs.get(a, ()) for a in inner):
            self.left.append((e["name"], "a relative jump from elsewhere lands inside it"))
            return None
        for a, name in inner.items():  # (others reach these with jp and call: by number does it)
            self.defines[name] = self.at(a)
        self.placed += 1
        self.done[flat] = True
        return [f"; documented in assembly: {e['file']}", *text.rstrip().splitlines(), ""]

    def bank(self, b: int, notes: dict[str, list[str]]) -> str:
        lo, hi = b * BANK, min((b + 1) * BANK, self.size)
        lines = [f".BANK {b} SLOT {self.base[b] >> 14}", ".ORG $0000", f'.SECTION "Bank {b}" FORCE']
        p, pending = lo, []

        def flush():
            for k in range(0, len(pending), 16):
                lines.append("    .db " + ", ".join(f"${v:02x}" for v in pending[k:k + 16]))
            pending.clear()
        while p < hi:
            if p in self.documented and (body := self.substitute(p, self.documented[p])) is not None:
                flush()
                lines += [f"; {t}" for t in notes.get(self.documented[p]["name"], [])] + body
                p += self.documented[p]["size"]
                continue
            if p in self.labels:
                flush()
                lines += [f"; {t}" for t in notes.get(self.labels[p], [])] + [f"{self.labels[p]}:"]
            if p in self.emitted:
                flush()
                text, ln, _cpu = self.emitted[p]
                lines.append("    " + self.operand(p, text))
                p += ln
            else:
                pending.append(self.image[p])
                p += 1
        flush()
        return "\n".join(lines + [".ENDS", ""])

    def used_names(self) -> None:
        """Names a documented routine uses that no label here gives: by number (jp and call reach them that way)."""
        placed = set(self.labels.values())
        functions = {f["name"]: f["cpu"] for f in self.funcs if f.get("name")}
        keep = {}
        for flat, e in self.documented.items():
            text = (ROOT / e["file"]).read_text(encoding="utf-8")
            used = {w for line in text.splitlines() for w in WORD.findall(line.split(";")[0])}
            missing = {n for n in used if n in functions and n not in placed and n not in set(GLOBAL.findall(text))}
            if missing & set(RELATIVE.findall(text)):
                self.left.append((e["name"], f"it jumps relatively to {', '.join(sorted(missing))}, which has no label "
                                             "here"))
                continue
            self.defines.update({n: functions[n] for n in missing})
            keep[flat] = e
        self.documented = keep


HW_PORTS: dict[tuple[int, bool], str] = {}
HW_MAPPER: dict[int, str] = {}


def hardware() -> None:
    """The hardware's names, as include/hardware.inc defines them."""
    names = {}
    for line in (ROOT / "include" / "hardware.inc").read_text(encoding="utf-8").splitlines():
        if (m := re.match(r"^\.DEFINE (\w+) \$([0-9A-Fa-f]+)$", line)):
            names[m.group(1)] = int(m.group(2), 16)
    for name, v in names.items():
        if v >= 0xFFFC:
            HW_MAPPER[v] = name
        else:
            for write in (False, True):
                HW_PORTS.setdefault((v, write), name)
    for name, v in names.items():  # (a port two names share: the PSG is written, the VDP's status read)
        if name == "PortPSG":
            HW_PORTS[(v, True)] = name
        if name == "PortVDPStatus":
            HW_PORTS[(v, False)] = name


def main(argv: list[str]) -> int:
    image = ROOT / B["image"]
    if not image.exists():
        fail(f"put your own copy of the game here as {B['image']}")
    data = image.read_bytes()
    if len(data) % BANK == 0x200:
        data = data[0x200:]  # (a copier's header in front)
    if hashlib.sha1(data).hexdigest() != B["sha1"]:
        fail(f"{B['image']} isn't the version this project is for (its sha1 differs)")
    asm, link = tools()
    hardware()
    folder = OUT / "disassembly"
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)
    print("disassembling your copy (with the project's names)")
    d = Disassembly(data, documented="--no-documented" not in argv)
    d.decode()
    d.name_targets()
    d.used_names()
    notes = comments()
    banks = [d.bank(b, notes) for b in range(d.banks)]
    left = {name for name, _ in d.left}
    for e in d.documented.values():  # (one the walk never reached the start of: inside what came before)
        if e["name"] not in left and not d.done.get(e["flat"]):
            d.left.append((e["name"], "its start falls inside what comes before it here"))
    for name, why in d.left:
        print(f"left as bytes: {name}: {why}")
    names = (ROOT / "documented" / "names.inc").read_text(encoding="utf-8") if (ROOT / "documented" / "names.inc").exists() else ""
    names += "".join(f".DEFINE {n} ${v:04X}\n" for n, v in sorted(d.defines.items()))
    (folder / "names.inc").write_text(names, encoding="utf-8")
    shutil.copyfile(ROOT / "include" / "hardware.inc", folder / "hardware.inc")
    size = BANK if len(data) >= BANK else len(data)
    game = [".MEMORYMAP", "DEFAULTSLOT 0", "SLOT 0 $0000 $4000", "SLOT 1 $4000 $4000", "SLOT 2 $8000 $4000", ".ENDME",
            ".ROMBANKMAP", f"BANKSTOTAL {d.banks}", f"BANKSIZE ${size:04X}", f"BANKS {d.banks}", ".ENDRO",
            '.INCLUDE "hardware.inc"', '.INCLUDE "names.inc"']
    for b, text in enumerate(banks):
        (folder / f"bank_{b:03d}.asm").write_text(text, encoding="utf-8")
        game.append(f'.INCLUDE "bank_{b:03d}.asm"')
    (folder / "game.asm").write_text("\n".join(game) + "\n", encoding="utf-8")
    (folder / "link.txt").write_text("[objects]\ngame.o\n", encoding="utf-8")
    print(f"{d.placed} documented routines in place of their bytes")
    rom = f"game.{'gg' if B['image'].endswith('.gg') else 'sms'}"
    run([asm, "-o", "game.o", "game.asm"], folder)
    run([link, "-S", "-r", "link.txt", rom], folder)
    built = (folder / rom).read_bytes()
    shutil.copyfile(folder / rom, OUT / rom)
    if built == data:
        print(f"identical: build/{rom} is your copy of the game, byte for byte")
        return 0
    at = next((i for i, (a, b) in enumerate(zip(built, data)) if a != b), min(len(built), len(data)))
    print(f"differs: build/{rom} first differs from your copy at ${at:06x} ({len(built)} vs {len(data)} bytes)")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
