#!/usr/bin/env python3
"""Build this Game Boy project and check the result against your own copy of the game, byte for byte.

    python build.py                  disassemble your copy, build, compare
    python build.py --fix-checksums  the same, then let rgbfix write the header's checksums (after you change it)
    python build.py --no-documented  without the documented routines (their bytes, as mgbdis writes them)

The game is assembly (RGBDS). Your copy, baserom.gb or baserom.gbc, is disassembled with mgbdis into
build/disassembly/ on every build, with the project's names (baserom.sym, which mgbdis reads next to the ROM) and
its notes as comments (comments.txt); each routine documented in assembly (documented/) goes in place of its bytes;
RGBDS rebuilds it. Edit the names, comments and documented routines here; the disassembly itself is made from your
copy and stays out of git. Generated by decomp.wtf (https://decomp.wtf).
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
B = json.loads((ROOT / "build.json").read_text(encoding="utf-8"))
OUT = ROOT / "build"
LABEL = re.compile(r"^([A-Za-z_][\w@#$]*)::?\s*$")
DATA = re.compile(r"^\s+db\s+(\S.*)$", re.I)  # a line of bytes, as mgbdis writes them
GLOBAL = re.compile(r"^\s*([A-Za-z_][\w@#$]*)::?", re.M)  # a routine's own (global) labels
JUMP = re.compile(r"^(\s+(?:call|jp|jr)\s+(?:(?:nz|z|nc|c)\s*,\s*)?)\$([0-9a-fA-F]{4})\b", re.I)


def fail(msg: str) -> None:
    sys.exit(f"error: {msg}")


def tools() -> tuple[Path, Path]:
    """(mgbdis.py, the folder with rgbasm/rgblink/rgbfix): decomp.wtf's pinned ones when it's installed, else
    MGBDIS (the path of mgbdis.py) and RGBDS on PATH."""
    try:
        from decompnet import toolchains

        mgbdis = next(iter(toolchains.path("mgbdis").glob("*/mgbdis.py")), None)
        rgbds = toolchains.path("rgbds")
        if mgbdis and (rgbds / "rgbasm").exists():
            return mgbdis, rgbds
    except ImportError:
        pass
    mgbdis = os.environ.get("MGBDIS")
    rgbasm = shutil.which("rgbasm")
    if not (mgbdis and Path(mgbdis).is_file() and rgbasm):
        fail("needs mgbdis and RGBDS: install decomp.wtf (it pins both), or put RGBDS on PATH and set MGBDIS to "
             "mgbdis.py's path")
    return Path(mgbdis), Path(rgbasm).parent


def run(argv: list, cwd: Path) -> None:
    proc = subprocess.run([str(a) for a in argv], cwd=cwd, capture_output=True, text=True, encoding="utf-8",
                          errors="replace")
    if proc.returncode != 0:
        fail(f"{Path(str(argv[0])).name} failed:\n{(proc.stdout + proc.stderr).strip()[-2000:]}")


def comments() -> dict[str, list[str]]:
    """label -> its comment lines, from comments.txt (`Label: text`, one line each)."""
    out: dict[str, list[str]] = {}
    path = ROOT / "comments.txt"
    for line in path.read_text(encoding="utf-8").splitlines() if path.exists() else []:
        label, sep, text = line.partition(": ")
        if sep and LABEL.match(label + ":"):
            out.setdefault(label, []).append(text)
    return out


def annotate(folder: Path, notes: dict[str, list[str]]) -> int:
    """Put each label's comments above it in the disassembly; returns how many labels got some."""
    done = 0
    for f in sorted(folder.glob("bank_*.asm")):
        lines, out = f.read_text(encoding="utf-8").splitlines(), []
        for line in lines:
            m = LABEL.match(line)
            if m and m.group(1) in notes:
                out += [f"; {text}" for text in notes[m.group(1)]]
                done += 1
            out.append(line)
        f.write_text("\n".join(out) + "\n", encoding="utf-8")
    return done


def documented(folder: Path) -> int:
    """Put each documented routine's text in place of its bytes (baserom.sym has a .data block over each, so mgbdis
    writes just its bytes there, after its label), with the includes it's written with: hardware.inc 6.0, its older
    names (mgbdis's own names among them) and the project's names it uses. Returns how many."""
    entries = B.get("documented") or []
    if not entries:
        return 0
    for f in ("hardware.inc", "hardware_compat.inc", "old_names.inc"):
        shutil.copyfile(ROOT / "include" / f, folder / f)
    names = (ROOT / "documented" / "names.inc").read_text(encoding="utf-8")
    game = (folder / "game.asm").read_text(encoding="utf-8")
    (folder / "game.asm").write_text(game.replace('INCLUDE "hardware.inc"', 'INCLUDE "hardware.inc"\nINCLUDE '
                                     '"hardware_compat.inc"\nINCLUDE "old_names.inc"\nINCLUDE "names.inc"', 1), encoding="utf-8")
    for bank in sorted({e["bank"] for e in entries}):
        path = folder / f"bank_{bank:03x}.asm"
        lines = path.read_text(encoding="utf-8").splitlines()
        for e in (e for e in entries if e["bank"] == bank):
            text = (ROOT / e["file"]).read_text(encoding="utf-8")
            own = set(GLOBAL.findall(text))
            at = next((k for k, line in enumerate(lines) if (m := LABEL.match(line)) and m.group(1) == e["name"]), None)
            if at is None:
                fail(f"{e['file']}: mgbdis put no label {e['name']} in bank_{bank:03x}.asm (is baserom.sym as exported?)")
            k, count, inner = at + 1, 0, [(e["name"], e["address"])]
            while count < e["size"] and k < len(lines):
                line = lines[k]
                if (m := LABEL.match(line)):
                    inner.append((m.group(1), e["address"] + count))
                elif (m := DATA.match(line.split(";")[0])):
                    count += len(m.group(1).split(","))
                elif line.strip() and not line.strip().startswith(";"):
                    break
                k += 1
            if count != e["size"]:
                fail(f"{e['file']}: bank_{bank:03x}.asm doesn't have its {e['size']} bytes after {e['name']} as data "
                     "(is baserom.sym as exported?)")
            lines[at:k] = [f"; documented in assembly: {e['file']}", *text.rstrip().splitlines(), ""]
            # a name the disassembly gives a place in it that its text doesn't: others may use it
            names += "".join(f"DEF {n} EQU ${a:04X}\n" for n, a in inner if n not in own)
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    # mgbdis names a jump's target only where it decoded code, and a documented routine's bytes are data to it: the
    # jumps and calls to one get its name back (in its own bank, or from any bank into bank 0, as mgbdis names them)
    starts = {(e["bank"], e["address"]): (GLOBAL.findall((ROOT / e["file"]).read_text(encoding="utf-8")) or [e["name"]])[0]
              for e in entries}
    for path in sorted(folder.glob("bank_*.asm")):
        bank = int(path.stem[5:], 16)

        def named(m: re.Match) -> str:
            addr = int(m.group(2), 16)
            label = starts.get((0 if addr < 0x4000 else bank, addr))
            return m.group(1) + label if label else m.group(0)
        text = path.read_text(encoding="utf-8")
        path.write_text("\n".join(JUMP.sub(named, line) for line in text.split("\n")), encoding="utf-8")
    (folder / "names.inc").write_text(names, encoding="utf-8")
    return len(entries)


def main(argv: list[str]) -> int:
    image = ROOT / B["image"]
    if not image.exists():
        fail(f"put your own copy of the game here as {B['image']}")
    if hashlib.sha1(image.read_bytes()).hexdigest() != B["sha1"]:
        fail(f"{B['image']} isn't the version this project is for (its sha1 differs)")
    mgbdis, rgbds = tools()
    disassembly = OUT / "disassembly"
    shutil.rmtree(disassembly, ignore_errors=True)
    OUT.mkdir(exist_ok=True)
    print("disassembling your copy with mgbdis (with the project's names)")
    run([sys.executable, mgbdis, image, "--output-dir", disassembly, "--overwrite"], ROOT)
    print(f"comments on {annotate(disassembly, comments())} labels")
    if "--no-documented" not in argv and (n := documented(disassembly)):
        print(f"{n} documented routines in place of their bytes")
    rom = f"game{image.suffix}"
    run([rgbds / "rgbasm", "-o", "game.o", "game.asm"], disassembly)
    run([rgbds / "rgblink", "-n", "game.sym", "-m", "game.map", "-o", rom, "game.o"], disassembly)
    # the header's checksums are in the disassembly as the original has them; rgbfix -v writes new ones
    run([rgbds / "rgbfix", *(["-v"] if "--fix-checksums" in argv else []), "-p", "255", rom], disassembly)
    built, original = (disassembly / rom).read_bytes(), image.read_bytes()
    shutil.copyfile(disassembly / rom, OUT / rom)
    if built == original:
        print(f"identical: build/{rom} is your copy of the game, byte for byte")
        return 0
    at = next((i for i, (a, b) in enumerate(zip(built, original)) if a != b), min(len(built), len(original)))
    print(f"differs: build/{rom} first differs from your copy at ${at:06x} ({len(built)} vs {len(original)} bytes)")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
